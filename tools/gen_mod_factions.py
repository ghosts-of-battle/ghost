def load_strings(*folders):
    """English text of the mods' $STR_ keys, for readable group names."""
    for folder in folders:
        for dp, _dn, fs in os.walk(folder):
            for f in fs:
                if f.lower() != "stringtable.xml":
                    continue
                t = open(os.path.join(dp, f), encoding="utf-8", errors="replace").read()
                for m in re.finditer(r'(?s)<Key ID="([^"]+)">(.*?)</Key>', t):
                    e = re.search(r"(?s)<(?:English|Original)>(.*?)</", m.group(2))
                    if e:
                        STRINGS[m.group(1).lower()] = e.group(1).strip()


def readable(u):
    d = str(u.get("displayname") or "")
    if d.startswith("$"):
        d = STRINGS.get(d[1:].lower(), "")
    if not d or d.startswith("$"):
        d = re.sub(r"(?i)^(tmt_|min_rf_|o_|pla_|placv_)", "", u["class"]).replace("_", " ")
    d = re.sub(r"[  -​ ]", " ", d).replace('"', "'")
    return d.encode("ascii", "replace").decode("ascii")


