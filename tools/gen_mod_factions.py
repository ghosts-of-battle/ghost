def pick_can(weapons, w, camo):
    """The base-game suppressor for weapon w, or None: from the CBA slot its MuzzleSlot inherits."""
    cur, hops, slot = w, 0, None
    while cur in weapons and hops < 30 and slot is None:
        slot = weapons[cur].get("muzzle_parent")
        cur, hops = weapons[cur].get("parent"), hops + 1
    cans = CANS.get((slot or "").lower())
    if not cans:
        return None
    for word in CAN_PREFER.get(camo, ()):
        for c in cans:
            if word in c.lower().replace("muzzle_snds_", ""):     # "snds" itself holds "snd"
                return c
    return cans[0]


