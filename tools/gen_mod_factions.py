def class_blocks(text):
    """Top-level classes inside the first `class CfgVehicles {` (or the given table): name -> (parent, text)."""
    out = collections.OrderedDict()
    for m in re.finditer(r"(?m)^    class (\S+?)\s*:\s*(\S+)\s*\{", text):
        i, d = m.end(), 1
        while d:
            d += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        j = text.find("\n", i)
        out[m.group(1)] = (m.group(2), text[m.start():j + 1 if j >= 0 else i])
    return out


def externs(text):
    m = re.search(r"class CfgVehicles \{\n(.*?)\n\n", text, re.S)
    return re.findall(r"(?m)^    class (\S+);", m.group(1)) if m else []


def group_blocks(text, category):
    """The text of one CfgGroups category (`class Infantry {...}`) at the faction level."""
    m = re.search(r"(?m)^            class %s \{" % category, text)
    if not m:
        return None
    i, d = m.end(), 1
    while d:
        d += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return text[m.start():i] + ";"


