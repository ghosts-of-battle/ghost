class Faction:
    def __init__(self, addon, display, side, tier, flag, icon, priority):
        self.addon, self.display, self.side, self.tier = addon, display, side, tier
        self.flag, self.icon, self.priority = flag, icon, priority
        self.decl = set()                  # source classes to declare
        self.blocks = []                   # CfgVehicles class texts
        self.units = []                    # our class names (QGVAR form names)
        self.men = {}                      # role -> [our class]
        self.sf = {}                       # special forces sets: name -> role -> [our class]
        self.veh = collections.defaultdict(list)   # kind -> [our class]
        self.patches = set()
        self.kept_groups = []              # verbatim category texts
        self.weapons_text = None
        self.extra_decl = []
        self.requires_ghost = set()
        self.names = {}
        self.weapons_db = None             # the mod's CfgWeapons index, for suppressed presets
        self.camo = "woodland"
        self.presets = {}                  # weapon -> base-game suppressor
        self.units_db = {}                 # the mod's CfgVehicles index by lower-case class, for uniform wearers
        self.wearers = {}                  # uniform -> its wearer, for uniforms this side may not wear

    def gv(self, src):
        return "GVAR(%s)" % src

    def add_man(self, u, fa, uniform=None, sf=None, crewset=None):
        src = u["class"]
        lines = ["    class %s: %s {" % (self.gv(src), src),
                 "        scope = 2;", "        scopeCurator = 2;", "        author = QAUTHOR;",
                 "        side = %d;" % self.side, "        faction = QUOTE(ADDON);",
                 '        editorSubcategory = "%s";' % ("EdSubcat_Personnel_SpecialForces" if sf else "EdSubcat_Personnel"),
                 '        vehicleClass = "%s";' % ("MenRecon" if sf else "Men")]
        worn = uniform or u.get("uniformclass")
        if worn and self.side_barred(worn):
            lines.append("        uniformClass = QGVAR(%s);" % worn)
        elif uniform:
            lines.append('        uniformClass = "%s";' % uniform)
        wl = u.get("weapons") or []
        if self.weapons_db is not None and self.tier >= 3 and wl:
            new_w = []
            for w in wl:
                info = self.weapons_db.get(w) or {}
                typ = str(info.get("type"))
                if (typ == "1" or (typ == "2" and self.tier >= 4)) and not re.search(r"(?i)_sd$|snds", w):
                    can = pick_can(self.weapons_db, w, self.camo)
                    if can:
                        self.presets[w] = can
                        new_w.append("QGVAR(%s_snds)" % w)
                        continue
                new_w.append('"%s"' % w)
            if new_w != ['"%s"' % w for w in wl]:
                arr = ", ".join(new_w)
                lines += ["        weapons[] = {%s};" % arr, "        respawnWeapons[] = {%s};" % arr]
        mags = u.get("magazines") or []
        if fa is not None and mags:
            swap = {}
            for m in set(mags):
                takers = [w for w in (u.get("weapons") or []) if fa.accepts(w, m)]
                if not takers:
                    continue                      # nothing he carries takes it: leave it alone
                rep = fa.magazine_for(m, self.tier)
                if rep:
                    swap[m] = rep
                    for w in takers:
                        fa.note_weapon(w, [m])
            new = [swap.get(m, m) for m in mags]
            if new != mags:
                arr = ", ".join('"%s"' % m for m in new)
                lines += ["        magazines[] = {%s};" % arr, "        respawnMagazines[] = {%s};" % arr]
        lines.append("    };")
        self.blocks.append("\n".join(lines))
        self.decl.add(src)
        self.units.append(src)
        r = role(src, u.get("displayname"))
        target = self.sf.setdefault(sf, {}) if sf else self.men
        target.setdefault(r, []).append(src)
        return src

    def side_barred(self, uniform):
        """True when this faction's side is not in the modelSides of the uniform's wearer - the game then
        refuses the uniform ("Uniform ... is not allowed for soldier class ..." in the RPT). TMT's uniforms
        are all worn by B_Soldier_base_F children ({3,1}), so none of them fit ghost's OPFOR or
        independent Turks. Such a uniform gets a ghost twin whose wearer allows every side (wearer_text)."""
        wearer = (self.weapons_db or {}).get(uniform, {}).get("uniformclass")
        w = self.units_db.get(str(wearer).lower()) if wearer else None
        if w is None:
            return False
        sides = w.get("modelsides")
        if sides is None:
            anc = [a.lower() for a in w.get("ancestry") or []]
            sides = next((v for k, v in (("soldierwb", [3, 1]), ("soldiereb", [3, 0]), ("soldiergb", [3, 2])) if k in anc), None)
        if sides is None or self.side in [int(x) for x in sides]:
            return False
        self.wearers[uniform] = w["class"]
        return True

    def wearer_text(self):
        """CfgVehicles and CfgWeapons lines for the uniform twins side_barred asked for."""
        if not self.wearers:
            return [], [], [], []
        vdecl, vbody, wdecl, wbody = [], [], ["    class ItemInfo;"], []
        for uni in sorted(self.wearers, key=str.lower):
            wearer = self.wearers[uni]
            vdecl.append("    class %s;" % wearer)
            vbody.append("\n".join(["    class GVAR(%s): %s {" % (wearer, wearer), "        scope = 1;", "        scopeCurator = 0;",
                                    "        author = QAUTHOR;", "        modelSides[] = {0, 1, 2, 3};", "    };"]))
            wdecl.append("    class %s;" % uni)
            wbody += ["    class GVAR(%s): %s {" % (uni, uni), "        scope = 1;", "        author = QAUTHOR;",
                      "        class ItemInfo: ItemInfo {", "            uniformClass = QGVAR(%s);" % wearer, "        };", "    };"]
        return vdecl, vbody, wdecl, wbody

