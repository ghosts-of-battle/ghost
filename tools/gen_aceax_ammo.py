#!/usr/bin/env python
"""Generate addons/aceax_ammo's XtdGear data from the mission's magazine list.

THE ARSENAL'S AMMO PANEL, COLLAPSED - BY ROUND TYPE (user, 2026-08-29: "the
ammo should be by type like 328 or 329 etc"). The mission arsenal lists over a
thousand magazines. One row per ROUND TYPE in one MAGAZINE FORM - "100Rnd 6.5mm
Mk328", "30Rnd 5.56 Mk332 AP", "30Rnd 6.5mm Mk329 (MSBS)" - and under it, in
the option panel, the things that do not change what the round does:

    tracer   Ball / Red / Green / Yellow / White / Blue / Orange / IR / Dim
    finish   Default / Black / Khaki / Tan / Sand / Coyote / Green ...
    colour   for smoke, flares and chemlights - their colour IS the variant

Calibre, capacity, magazine model (PMAG, EMAG, MSBS, Box) and the load
(Mk328 vs Mk329 vs Mk331 AP vs XM892) each keep their own row: those are what
the player is choosing between on purpose.

THE FIRST VERSION PEELED SUFFIXES and the names do not nest that way: the
finish sits BEFORE the tracer marker ("..._Mk328_Black_T_Red"), the FA tracer
marker is "_T_<Colour>" with the ball round carrying nothing, and the smoke
and flare colours are CamelCase compounds ("SmokeShellBlue", "FlareCIR"). So
one round type came out as four rows - "Mk328", "Mk328 T", "Mk328 Black T",
"Mk328 Khaki T" - and the ball round was never in the family at all. This
version TOKENISES the class name instead: every token is either a tracer
marker, a finish, a colour, or part of the stem, and the stem is the family.

This writes the DATA in ACE Arsenal Extended's XtdGearModels / XtdGearInfos
schema; the runtime that reads it lives in addons/aceax_ammo/functions (ACEAX
itself has no magazine kind). Display names are NOT baked in - the runtime
reads them from config, because several of these magazines come from CDLCs
whose configs are encrypted.

Re-run after changing the mission's magazine list:
    python tools/gen_aceax_ammo.py            # writes the two .hpp
    python tools/gen_aceax_ammo.py --report   # prints every family and its members
"""

import io
import os
import re
import sys
from collections import defaultdict, OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
ADDON = os.path.join(REPO, "addons", "aceax_ammo")
MISSION = r"D:\Dropbox\Documents\Arma 3 - Other Profiles\YonV\missions\2040\Task_Force_Roomba_dev.Tanoa"
MAGS = os.path.join(MISSION, "config", "arsenal", "common", "magazines.hpp")

HDR = ("// Generated by tools/gen_aceax_ammo.py - re-run rather than hand-edit.\n"
       "//\n")

# ---------------------------------------------------------------------------
# THE VOCABULARY
# ---------------------------------------------------------------------------
# colour token (lowercase) -> (value key, label). The same words serve three
# axes: after a tracer marker they are the tracer's colour, on a smoke or a
# flare they are the colour, anywhere else on a magazine they are its finish.
COLOURS = OrderedDict([
    ("red", ("red", "Red")),
    ("green", ("green", "Green")),
    ("yellow", ("yellow", "Yellow")),
    ("white", ("white", "White")),
    ("blue", ("blue", "Blue")),
    ("orange", ("orange", "Orange")),
    ("purple", ("purple", "Purple")),
    ("ir", ("ir", "IR")),
    ("cir", ("ir", "IR")),
    ("dim", ("dim", "Dim")),
])
# finish token (lowercase) -> (value key, label): the magazine body's paint
FINISHES = OrderedDict([
    ("black", ("black", "Black")),
    ("blk", ("black", "Black")),
    ("khaki", ("khaki", "Khaki")),
    ("khk", ("khaki", "Khaki")),
    ("tan", ("tan", "Tan")),
    ("sand", ("sand", "Sand")),
    ("snd", ("sand", "Sand")),
    ("coy", ("coyote", "Coyote")),
    ("coyote", ("coyote", "Coyote")),
    ("olive", ("olive", "Olive")),
    ("oli", ("olive", "Olive")),
    ("grn", ("green", "Green")),
    ("green", ("green", "Green")),   # the green PMAG; only off a tracer marker
    ("wdl", ("woodland", "Woodland")),
    ("hex", ("hex", "Hex")),
    ("ghex", ("ghex", "Green Hex")),
])
# tokens that mark "the next colour is the tracer's": FA's "_T_Red", the base
# game's and ACE's "_Tracer", "_Tracer_Red", "_Tracer_Dim"
TRACER_MARKERS = ("t", "tracer")
# CamelCase compounds that carry a colour on their tail: SmokeShellBlue,
# SmokeBlue, FlareGreen, FlareCIR, HiBlue (ACE's chemlights)
COMPOUND = re.compile(r"^(SmokeShell|Smoke|Flare|Hi)(Red|Green|Yellow|White|Blue|Orange|Purple|IR|CIR)$")
# a stem is a pyrotechnic - its colour is the variant, not a finish
PYRO = re.compile(r"smoke|flare|chemlight|handflare|signalflare", re.I)

AXES = OrderedDict([
    ("tracer", "Tracer"),
    ("colour", "Colour"),
    ("finish", "Finish"),
])
# the value a member has on an axis when its name says nothing about it
DEFAULT = {
    "tracer": ("ball", "Ball"),
    "colour": ("default", "Default"),
    "finish": ("default", "Default"),
}


def classify(name):
    """(stem tokens, {axis: (key, label)}) for one magazine class."""
    raw = name.split("_")
    tokens = []
    for t in raw:
        m = COMPOUND.match(t)
        if m:
            tokens += [m.group(1), m.group(2)]
        else:
            tokens.append(t)

    stem = []
    vals = {}
    i = 0
    n = len(tokens)
    while i < n:
        t = tokens[i]
        low = t.lower()
        nxt = tokens[i + 1].lower() if i + 1 < n else ""
        # a tracer marker, with or without a colour after it
        if low in TRACER_MARKERS and (nxt in COLOURS or low == "tracer"):
            if nxt in COLOURS:
                vals["tracer"] = COLOURS[nxt]
                i += 2
            else:
                vals["tracer"] = ("tracer", "Tracer")
                i += 1
            continue
        stem.append(t)
        i += 1

    # colours and finishes are decided once the stem is known, because the
    # same word is a finish on a magazine and THE colour on a smoke grenade
    pyro = bool(PYRO.search("_".join(stem)))
    kept = []
    for t in stem:
        low = t.lower()
        if low in COLOURS and pyro:
            vals["colour"] = COLOURS[low]
            continue
        if low in FINISHES and not pyro:
            vals["finish"] = FINISHES[low]
            continue
        kept.append(t)
    return kept, vals


def slug(stem_key):
    s = re.sub(r"[^A-Za-z0-9]+", "_", stem_key).strip("_").lower()
    return "ghost_ammo_" + s


def read_mags():
    if not os.path.exists(MAGS):
        sys.stderr.write("!! not found: %s\n" % MAGS)
        return []
    txt = io.open(MAGS, encoding="utf-8", errors="replace").read()
    # only the magazines[] array, not the surrounding prose
    return sorted(set(re.findall(r'"([A-Za-z0-9_]+)"', txt)))


def crlf(path, lines):
    with io.open(path, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("\n".join(lines).rstrip("\n") + "\n")


def build(mags):
    """{stem key: (label, {member: vals}, {axis: {key: label}})} for every
    family worth a row - more than one member, differing on some axis."""
    fam = defaultdict(dict)
    labels = {}
    for m in mags:
        stem, vals = classify(m)
        key = "_".join(stem).lower()
        fam[key][m] = vals
        labels.setdefault(key, " ".join(stem))

    groups = {}
    for key, members in fam.items():
        if len(members) < 2:
            continue
        live = OrderedDict()
        for axis in AXES:
            seen = OrderedDict()
            for m, vals in members.items():
                k, label = vals.get(axis, DEFAULT[axis])
                # the plain smoke is white smoke, and says so
                if axis == "colour" and k == "default" and re.search(r"smoke", key):
                    k, label = "white", "White"
                seen[k] = label
            if len(seen) > 1:
                # the plain one first, then the vocabulary's own order, so the
                # buttons read Ball / Red / Green ... on every magazine alike
                order = [DEFAULT[axis][0], "white", "tracer"] + [v[0] for v in COLOURS.values()] + [v[0] for v in FINISHES.values()]
                live[axis] = OrderedDict(sorted(seen.items(), key=lambda kv: order.index(kv[0]) if kv[0] in order else 999))
        if live:
            groups[key] = (labels[key], members, live)
    return groups


def value_of(vals, axis, key):
    k, _label = vals.get(axis, DEFAULT[axis])
    if axis == "colour" and k == "default" and re.search(r"smoke", key):
        k = "white"
    return k


def main():
    mags = read_mags()
    if not mags:
        return 2
    groups = build(mags)

    if "--report" in sys.argv:
        for key in sorted(groups):
            label, members, live = groups[key]
            axes = ", ".join("%s: %s" % (a, "/".join(seen.values())) for a, seen in live.items())
            print("%s  [%d]  %s" % (label, len(members), axes))
            for m in sorted(members):
                print("    %s" % m)
        return 0

    # ---- XtdGearModels: one class per family, its axes and their values ----
    L = [HDR.rstrip("\n"),
         "// One class per family - one round type in one magazine form. `options[]`",
         "// names the axes that family varies on; each axis class lists its",
         "// values. This is ACEAX's schema - see the header of",
         "// tools/gen_aceax_ammo.py for why we use it for magazines, which ACEAX",
         "// itself does not know about.",
         "",
         "class XtdGearModels {",
         "    class CfgMagazines {"]
    for key in sorted(groups):
        label, members, live = groups[key]
        L += ["        class %s {" % slug(key),
              '            label = "%s";' % label,
              "            options[] = {%s};" % ", ".join('"%s"' % a for a in live),
              ""]
        for axis, seen in live.items():
            L += ["            class %s {" % axis,
                  '                label = "%s";' % AXES[axis],
                  "                values[] = {%s};" % ", ".join('"%s"' % k for k in seen),
                  ""]
            for k, lab in seen.items():
                L += ["                class %s { label = \"%s\"; };" % (k, lab)]
            L += ["            };"]
        L += ["        };"]
    L += ["    };", "};"]
    crlf(os.path.join(ADDON, "XtdGearModels.hpp"), L)

    # ---- XtdGearInfos: every magazine, its family and where it sits ----
    L = [HDR.rstrip("\n"),
         "// Every magazine that belongs to a family, naming the family and its",
         "// value on each of that family's axes. A magazine not listed here is",
         "// left alone and keeps its own row.",
         "",
         "class XtdGearInfos {",
         "    class CfgMagazines {"]
    listed = 0
    for key in sorted(groups):
        label, members, live = groups[key]
        for m in sorted(members):
            vals = members[m]
            parts = ['            model = "%s";' % slug(key)]
            for axis in live:
                parts.append('            %s = "%s";' % (axis, value_of(vals, axis, key)))
            L += ["        class %s {" % m] + parts + ["        };"]
            listed += 1
    L += ["    };", "};"]
    crlf(os.path.join(ADDON, "XtdGearInfos.hpp"), L)

    saved = listed - len(groups)
    print("wrote  addons/aceax_ammo: %d families over %d magazines" % (len(groups), listed))
    print("       arsenal rows: %d -> %d  (%d fewer)" % (len(mags), len(mags) - saved, saved))
    axis_count = defaultdict(int)
    for _k, (_l, _m, live) in groups.items():
        for a in live:
            axis_count[a] += 1
    print("       families by axis: %s"
          % ", ".join("%s %d" % (a, n) for a, n in sorted(axis_count.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
